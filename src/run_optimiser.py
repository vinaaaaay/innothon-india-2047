INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
STACK = ["Coal", "Hydro", "Gas", "Wind", "Solar", "Nuclear", "Bioenergy & other"]       # bottom to top
COLOR = {"Coal": "#e34948", "Hydro": "#2a78d6", "Gas": "#eb6834", "Wind": "#1baf7a", "Solar": "#eda100",
         "Nuclear": "#e87ba4", "Bioenergy & other": "#008300"}


def _fold(df: pd.DataFrame, keys: list[str]) -> pd.DataFrame:
    d = df.copy()
    d["source"] = d["source"].replace({"Bioenergy": "Bioenergy & other", "Other": "Bioenergy & other"})
    return d.groupby(keys + ["source"], as_index=False)["twh"].sum()


def _style(ax, title: str, ylabel: str) -> None:
    ax.set_facecolor(SURFACE)
    ax.set_title(title, loc="left", fontsize=12, color=INK, pad=12)
    ax.set_ylabel(ylabel, color=INK2, fontsize=9)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for sp in ("top", "right", "left"):
        ax.spines[sp].set_visible(False)
    ax.spines["bottom"].set_color(GRID)
    ax.tick_params(colors=INK2, labelsize=9, length=0)


def _stack(ax, table: pd.DataFrame, x: np.ndarray, width: float, label_min: float, legend: bool = True) -> None:
    bottom = np.zeros(len(table))
    for src in STACK:
        v = table[src].values if src in table else np.zeros(len(table))
        ax.bar(x, v, width, bottom=bottom, color=COLOR[src], edgecolor=SURFACE, linewidth=1.2, label=src if legend else None)
        for xi, vi, bi in zip(x, v, bottom):
            if vi >= label_min:
                ax.text(xi, bi + vi / 2, f"{vi:,.0f}", ha="center", va="center", fontsize=7.5, color="white" if src in ("Coal", "Hydro", "Bioenergy & other") else INK)
        bottom += v
    for xi, tot in zip(x, bottom):
        ax.text(xi, tot + bottom.max() * 0.012, f"{tot:,.0f}", ha="center", va="bottom", fontsize=8.5, color=INK, fontweight="bold")


def make_figures(nat, zone, summary, zb) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    # 5. national mix over time
    d = _fold(nat[nat.strategy == HEADLINE], ["year"]).pivot(index="year", columns="source", values="twh")
    fig, ax = plt.subplots(figsize=(9, 5.2), facecolor=SURFACE)
    _stack(ax, d, np.arange(len(d)), 0.62, label_min=d.sum(axis=1).max() * 0.035)
    ax.set_xticks(np.arange(len(d)))
    ax.set_xticklabels([str(y) for y in d.index])
    _style(ax, f"India's generation mix to 2047 - {HEADLINE} strategy", "TWh per year (utility generation)")
    hnd, lab = ax.get_legend_handles_labels()
    ax.legend(hnd[::-1], lab[::-1], frameon=False, fontsize=8, loc="upper left", labelcolor=INK2)
    fig.tight_layout()
    fig.savefig(FIGURES / "05_national_mix.png", dpi=160)
    plt.close(fig)

    # 6. zone mix, 2025 vs 2047 (small multiples, one y-scale)
    zf = _fold(zone[zone.strategy == HEADLINE], ["year", "zone"])
    fig, axes = plt.subplots(1, 6, figsize=(13, 4.6), sharey=True, facecolor=SURFACE)
    top = zf[zf.year.isin([2025, 2047])].groupby(["year", "zone"])["twh"].sum().max()
    for ax, zname in zip(axes, ZONES):
        t = zf[(zf.zone == zname) & zf.year.isin([2025, 2047])].pivot(index="year", columns="source", values="twh").fillna(0)
        _stack(ax, t, np.arange(2), 0.7, label_min=top * 0.05, legend=zname == ZONES[0])
        ax.set_xticks([0, 1])
        ax.set_xticklabels(["2025", "2047"])
        _style(ax, zname, "TWh per year" if zname == ZONES[0] else "")
    hnd, lab = axes[0].get_legend_handles_labels()
    fig.legend(hnd[::-1], lab[::-1], frameon=False, fontsize=8, loc="upper right", labelcolor=INK2, ncol=7, bbox_to_anchor=(0.99, 1.0))
    fig.suptitle(f"Generation mix by zone, 2025 and 2047 - {HEADLINE}", x=0.01, ha="left", fontsize=13, color=INK)
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(FIGURES / "06_zone_mix.png", dpi=160)
    plt.close(fig)

    # 7. strategies compared in 2047
    three = ["Least cost", "Balanced", "Deep decarbonisation"]
    d = _fold(nat[(nat.year == 2047) & nat.strategy.isin(three)], ["strategy"]).pivot(index="strategy", columns="source", values="twh").reindex(three)
    s47 = summary[(summary.year == 2047)].set_index("strategy")
    fig, ax = plt.subplots(figsize=(9, 5.2), facecolor=SURFACE)
    _stack(ax, d, np.arange(3), 0.55, label_min=d.sum(axis=1).max() * 0.035)
    ax.set_xticks(np.arange(3))
    ax.set_xticklabels([f"{n}\n{s47.loc[n, 'emissions_mtco2']:,.0f} MtCO2  |  INR {s47.loc[n, 'avg_cost_inr_kwh']:.2f}/kWh" for n in three], fontsize=9)
    _style(ax, "Three strategies for 2047: mix, emissions and average cost", "TWh per year (utility generation)")
    hnd, lab = ax.get_legend_handles_labels()
    ax.legend(hnd[::-1], lab[::-1], frameon=False, fontsize=8, loc="upper left", bbox_to_anchor=(1.0, 1.0), labelcolor=INK2)
    fig.tight_layout()
    fig.savefig(FIGURES / "07_strategies_2047.png", dpi=160)
    plt.close(fig)

    # 8. net export by zone, 2025 vs 2047
    b = zb[(zb.strategy == HEADLINE) & zb.year.isin([2025, 2047])].pivot(index="zone", columns="year", values="net_export_twh").reindex(ZONES)
    fig, ax = plt.subplots(figsize=(9, 4.8), facecolor=SURFACE)
    x = np.arange(len(ZONES))
    for i, (yr, col) in enumerate([(2025, "#86b6ef"), (2047, "#1c5cab")]):
        bars = ax.bar(x + (i - 0.5) * 0.38, b[yr].values, 0.34, color=col, label=str(yr))
        for bar, v in zip(bars, b[yr].values):
            ax.text(bar.get_x() + bar.get_width() / 2, v + (8 if v >= 0 else -8), f"{v:+,.0f}", ha="center",
                    va="bottom" if v >= 0 else "top", fontsize=8, color=INK2)
    ax.axhline(0, color=INK2, linewidth=0.8)
    ax.set_xticks(x)
    ax.set_xticklabels(ZONES)
    _style(ax, f"Net export by zone (made minus needed) - {HEADLINE}", "TWh per year; positive = exporter")
    ax.legend(frameon=False, fontsize=8, loc="upper left", labelcolor=INK2)
    fig.tight_layout()
    fig.savefig(FIGURES / "08_zone_net_export.png", dpi=160)
    plt.close(fig)


if __name__ == "__main__":
    main()
