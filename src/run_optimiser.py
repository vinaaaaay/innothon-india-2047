"""Run the allocation optimiser for the named strategies and need cases.

Writes outputs/mix_*.csv, outputs/strategy_summary.csv, outputs/zone_balance.csv,
outputs/allocation_reasons.csv, outputs/build_pace.csv, outputs/monthly_dispatch.csv
and figures 05-08.
"""
import sys
from dataclasses import replace
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np
import pandas as pd

import compliance
import optimise as O
from config import FIGURES, MILESTONES, OUTPUTS, PROCESSED, ZONES

HEADLINE = "Balanced"
RUNS = [
    O.Params(name="Least cost", carbon_price=0.0),
    O.Params(name="Balanced", carbon_price=2000.0),
    O.Params(name="Deep decarbonisation", carbon_price=6000.0),
    O.Params(name="Balanced, low need (P10)", carbon_price=2000.0, need_case="p10"),
    O.Params(name="Balanced, high need (P90)", carbon_price=2000.0, need_case="p90"),
]


def gas_breakeven(inp: O.Inputs) -> pd.DataFrame:
    """How cheap must gas-fired generation be before the Balanced plan uses more of it?"""
    rows = []
    for c in (7.5, 6.5, 5.5, 4.5, 3.5):
        p = O.Params(name=f"gas at {c}", carbon_price=2000.0)
        p.cost = {**p.cost, "Gas": (c, 0.0)}
        sol, meta = O.solve(inp, p)
        t = O.tidy(sol, meta, inp)
        g = t["mix"][t["mix"].source == "Gas"].groupby("year")["twh"].sum()
        rows.append({"gas_cost_inr_kwh": c, **{f"gas_twh_{y}": g[y] for y in MILESTONES},
                     "gas_share_2047": g[2047] / t["summary"].set_index("year").loc[2047, "generation_twh"]})
    return pd.DataFrame(rows)


def ceiling_sensitivity(inp: O.Inputs) -> pd.DataFrame:
    """How much do the land and wind ceilings drive coal and emissions in 2047?"""
    cases = [("P50", "p50", 1.0, 1.0), ("P50, solar land 5 % instead of 3 %", "p50", 5 / 3, 1.0), ("P50, wind ceiling doubled", "p50", 1.0, 2.0),
             ("P50, both", "p50", 5 / 3, 2.0), ("P90", "p90", 1.0, 1.0), ("P90, both", "p90", 5 / 3, 2.0)]
    rows = []
    for label, need, sol_scale, wind_scale in cases:
        p = O.Params(name=label, carbon_price=2000.0, need_case=need)
        p.ceiling_scale = {"Solar": sol_scale, "Wind": wind_scale, "Hydro": 1.0}
        sol, meta = O.solve(inp, p)
        t = O.tidy(sol, meta, inp)
        g = t["mix"][t["mix"].year == 2047].groupby("source")["twh"].sum()
        s47 = t["summary"].set_index("year").loc[2047]
        rows.append({"case": label, "solar_twh": g["Solar"], "wind_twh": g["Wind"], "coal_twh": g["Coal"], "gas_twh": g["Gas"],
                     "nuclear_twh": g["Nuclear"], "emissions_mtco2": s47["emissions_mtco2"], "clean_share": s47["clean_share"],
                     "avg_cost_inr_kwh": s47["avg_cost_inr_kwh"]})
    return pd.DataFrame(rows)


def zone_cards(inp: O.Inputs, zone: pd.DataFrame, zb: pd.DataFrame, why: pd.DataFrame) -> str:
    """One evidence card per zone for the headline strategy: need, mix, local strengths, and what decided each source."""
    r = inp.res.reset_index()
    lines = [f"# Zone strategy cards - {HEADLINE} strategy, P50 need", "",
             "Generated by `src/run_optimiser.py`. All energy figures are TWh per year of utility generation.", ""]
    for z in ZONES:
        b = zb[(zb.strategy == HEADLINE) & (zb.zone == z)].set_index("year")
        m = zone[(zone.strategy == HEADLINE) & (zone.zone == z)].pivot(index="year", columns="source", values="twh")[O.REPORT_SOURCES]
        rz = r[r.zone == z]
        w = why[(why.strategy == HEADLINE) & (why.zone == z) & (why.year == 2047)].copy()
        w["src"] = w["source"].str.replace("_existing", "").str.replace("_new", "")
        states = ", ".join(rz.sort_values("area_km2", ascending=False)["state"].head(6))
        pos = b.loc[2047, "net_export_twh"]
        lines += [f"## {z}", "", f"Largest states: {states}.", "",
                  f"- **Need**: {b.loc[2025, 'need_twh']:,.0f} in 2025 to {b.loc[2047, 'need_twh']:,.0f} in 2047 "
                  f"({b.loc[2047, 'need_twh'] / b.loc[2025, 'need_twh']:.1f}x); share of India {b.loc[2025, 'need_share']:.0%} to {b.loc[2047, 'need_share']:.0%}.",
                  f"- **Made**: {b.loc[2025, 'made_twh']:,.0f} in 2025 to {b.loc[2047, 'made_twh']:,.0f} in 2047; "
                  f"net {'exporter' if pos > 0 else 'importer'} of {abs(pos):,.0f} in 2047.",
                  f"- **Local strengths**: solar ceiling {rz.solar_ceiling_twh.sum():,.0f} (mean irradiance "
                  f"{np.average(rz.ghi_kwh_m2_day, weights=rz.area_km2):.2f} kWh/m2/day), wind ceiling {rz.wind_ceiling_twh.sum():,.0f}, "
                  f"hydro ceiling {rz.hydro_ceiling_twh.sum():,.0f}; open land {np.average(rz.share_open.fillna(0), weights=rz.area_km2):.0%}, "
                  f"cropland {np.average(rz.share_cropland.fillna(0), weights=rz.area_km2):.0%}, forest {np.average(rz.share_forest.fillna(0), weights=rz.area_km2):.0%} of area.",
                  "", "| Source | 2025 | 2030 | 2040 | 2047 | Share 2047 | What decides the 2047 level |", "|---|---|---|---|---|---|---|"]
        tot47 = m.loc[2047].sum()
        for src in O.REPORT_SOURCES:
            if m[src].max() < 0.5:
                continue
            ws = w[(w.src == src) & (w.twh > 0.05)]
            reason = ws.groupby("reason")["twh"].sum().sort_values(ascending=False)
            txt = "; ".join(f"{k} ({v:,.0f})" for k, v in reason.head(2).items()) if len(reason) else "held at today's level"
            lines.append(f"| {src} | {m.loc[2025, src]:,.0f} | {m.loc[2030, src]:,.0f} | {m.loc[2040, src]:,.0f} | {m.loc[2047, src]:,.0f} | "
                         f"{m.loc[2047, src] / tot47:.0%} | {txt} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    inp = O.load_inputs()
    for name in ("base_mix_state", "monthly_shapes", "need_shape", "dispatch_bands", "emission_factors", "build_rates", "resources_state"):
        compliance.assert_clean(pd.read_csv(PROCESSED / f"{name}.csv"), name)

    out: dict[str, list] = {k: [] for k in ("mix", "why", "summary", "zone_balance", "monthly", "build")}
    for p in RUNS:
        sol, meta = O.solve(inp, p)
        if sol.status != "optimal":
            raise RuntimeError(f"{p.name}: {sol.status}")
        t = O.tidy(sol, meta, inp)
        for k, df in t.items():
            out[k].append(df.assign(strategy=p.name))
    res = {k: pd.concat(v, ignore_index=True) for k, v in out.items()}

    mix = res["mix"]
    nat = mix.groupby(["strategy", "year", "source"], as_index=False)["twh"].sum()
    zone = mix.groupby(["strategy", "year", "zone", "source"], as_index=False)["twh"].sum()
    zone["share_of_zone"] = zone["twh"] / zone.groupby(["strategy", "year", "zone"])["twh"].transform("sum")
    gas = gas_breakeven(inp)
    ceil = ceiling_sensitivity(inp)
    ceil.to_csv(OUTPUTS / "ceiling_sensitivity.csv", index=False)

    compliance.assert_clean(mix, "mix_state_source").to_csv(OUTPUTS / "mix_state_source.csv", index=False)
    zone.to_csv(OUTPUTS / "mix_zone_source.csv", index=False)
    nat.to_csv(OUTPUTS / "mix_national.csv", index=False)
    res["summary"].to_csv(OUTPUTS / "strategy_summary.csv", index=False)
    res["zone_balance"].to_csv(OUTPUTS / "zone_balance.csv", index=False)
    res["why"].to_csv(OUTPUTS / "allocation_reasons.csv", index=False)
    res["build"].to_csv(OUTPUTS / "build_pace.csv", index=False)
    res["monthly"].to_csv(OUTPUTS / "monthly_dispatch.csv", index=False)
    gas.to_csv(OUTPUTS / "gas_breakeven.csv", index=False)
    (OUTPUTS / "zone_strategy_cards.md").write_text(zone_cards(inp, zone, res["zone_balance"], res["why"]))

    # ---- report -------------------------------------------------------------------
    pd.set_option("display.width", 230)
    pd.set_option("display.max_rows", 200)
    order = O.REPORT_SOURCES
    h = nat[nat.strategy == HEADLINE].pivot(index="year", columns="source", values="twh")[order]
    h["Total"] = h.sum(axis=1)
    print(f"NATIONAL MIX - {HEADLINE} (TWh, utility basis)")
    print(h.round(0).to_string())
    print("\nshares (%):")
    print(h[order].div(h["Total"], axis=0).mul(100).round(1).to_string())

    s = res["summary"]
    cols = ["strategy", "year", "need_twh", "generation_twh", "storage_shift_twh", "curtailed_twh", "unserved_twh", "transfer_twh",
            "emissions_mtco2", "intensity_gco2_kwh", "clean_share", "avg_cost_inr_kwh"]
    print("\nSYSTEM SUMMARY")
    print(s[s.year.isin([2025, 2030, 2047])][cols].round({"need_twh": 0, "generation_twh": 0, "storage_shift_twh": 0, "curtailed_twh": 0,
          "unserved_twh": 2, "transfer_twh": 0, "emissions_mtco2": 0, "intensity_gco2_kwh": 0, "clean_share": 3, "avg_cost_inr_kwh": 2}).to_string(index=False))

    print("\n2047 MIX BY STRATEGY (TWh)")
    c = nat[nat.year == 2047].pivot(index="strategy", columns="source", values="twh")[order]
    print(c.round(0).to_string())

    print(f"\nZONE MIX 2047 - {HEADLINE} (TWh)")
    z = zone[(zone.strategy == HEADLINE) & (zone.year == 2047)].pivot(index="zone", columns="source", values="twh").reindex(ZONES)[order]
    z["Total"] = z.sum(axis=1)
    print(z.round(0).to_string())
    zb = res["zone_balance"]
    print("\nZONE BALANCE (made - need, TWh):")
    print(zb[(zb.strategy == HEADLINE) & zb.year.isin([2025, 2047])].pivot(index="zone", columns="year", values=["made_twh", "need_twh", "net_export_twh"]).reindex(ZONES).round(0).to_string())

    print(f"\nBUILD PACE - {HEADLINE}: how much of each period's allowed build is used")
    bp = res["build"][res["build"].strategy == HEADLINE].copy()
    bp["used_pct"] = bp["used_twh"] / bp["limit_twh"] * 100
    print(bp.pivot(index="source", columns="year", values="used_pct").round(0).to_string())
    print("shadow price of the national build limit (INR/kWh):")
    print(bp.pivot(index="source", columns="year", values="shadow_price_inr_kwh").round(2).to_string())

    why = res["why"]
    w47 = why[(why.strategy == HEADLINE) & (why.year == 2047)]
    print("\nWHY (2047, Balanced): TWh by source and binding reason")
    print(w47.groupby(["source", "reason"])["twh"].sum().round(0).to_string())

    md = res["monthly"]
    m47 = md[(md.strategy == HEADLINE) & (md.year == 2047)].set_index("month")
    print("\nMONTHLY 2047 (Balanced):")
    print(m47[["need_twh", "coal_twh", "gas_twh", "storage_shift_twh", "curtailed_twh", "marginal_cost_inr_kwh"]].round(1).T.to_string())

    print("\nGAS BREAK-EVEN (Balanced):")
    print(gas.round(2).to_string(index=False))

    print("\nCEILING SENSITIVITY (Balanced, 2047):")
    print(ceil.round({"solar_twh": 0, "wind_twh": 0, "coal_twh": 0, "gas_twh": 0, "nuclear_twh": 0, "emissions_mtco2": 0,
                      "clean_share": 3, "avg_cost_inr_kwh": 2}).to_string(index=False))

    make_figures(nat, zone, res["summary"], res["zone_balance"])


